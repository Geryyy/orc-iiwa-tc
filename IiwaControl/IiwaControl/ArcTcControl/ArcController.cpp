HRESULT CArcController::SetObjStatePS(PTComInitDataHdr pInitData)
{
	counter = 0;
	m_Trace.Log(tlVerbose, FENTERA);
	HRESULT hr = S_OK;
	IMPLEMENT_ITCOMOBJECT_EVALUATE_INITDATA(pInitData);

	// TODO: Add initialization code
	// 

	// ------------------- READ IN MUJOCO FILE -------------	
	// Create file access instance
	hr = m_spSrv->TcCreateInstance(CID_TcFileAccess, IID_ITcFileAccess, (PPVOID)(&m_spFileAccess));

	// Choose mjb file as per TwinCAT parameters
	std::string model_path = "C:\\TwinCAT\\3.1\\Boot\\";
	if (m_MujocoModel == ArcControllerMujocoModel::iiwa_hanging)
		model_path.append("iiwa_hanging.mjb");
	else if (m_MujocoModel == ArcControllerMujocoModel::iiwa_hanging_with_mass_gripped)
		model_path.append("iiwa_hanging_with_mass_gripped.mjb");
	else if (m_MujocoModel == ArcControllerMujocoModel::custom)
		model_path.append(m_CustomMujocoModelPath);
	else
		return E_FAIL;
	strcpy(m_Outputs.model_path, model_path.c_str());
	
	if (SUCCEEDED(hr)) {
		ITComObjectPtr spFileAccessObj = m_spFileAccess;
		hr = spFileAccessObj->TcSetObjState(TCOM_STATE_PREOP, m_spSrv, pInitData);
		if (SUCCEEDED(hr)) {
			// read Mujoco binary file (iiwa.mjb) from _Boot directory
			m_Trace.Log(tlVerbose, FENTERA "Reading MJB file!");
			// %BOOTPRJPATH% und %TC_TARGETPATH% funktionieren hier nicht, wieso?
			hr = readBinaryModel(model_path.c_str());
		}
	}
	// ------------------- MUJOCO END ----------------------
	
	arc::log::start_logging_twincat(m_TraceLevelMax, &m_Trace);
	m_Trace.Log(tlAlways, FLEAVEA "ARC initialized!", hr);
	m_Trace.Log(tlVerbose, FLEAVEA "hr=0x%08x", hr);
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from SAFEOP to OP
//
// Register with other TwinCAT objects
HRESULT CArcController::SetObjStateSO()
{
	m_Trace.Log(tlVerbose, FENTERA);
	HRESULT hr = S_OK;

	// TODO: Add any additional initialization

	// Initialize data pointer 
	hr = FAILED(hr) ? hr : InitDataPointer();

	// current time
	t = 0.0;

	// read cycle time from TcCom Module Parameter
	Ts = m_Ts;
	m_Trace.Log(tlAlways, FLEAVEA "Cycle Time Ts = %f", Ts);

	using namespace arc::Robots;
	using JointArray = Iiwa::JointArray;
	using JointVector = Iiwa::JointVector;


	// set controller parameter
	Iiwa::IiwaContrParam contr_param(false); // true..sim, false..lab
	JointArray f_c_slow_norm = contr_param.f_c_slow * (2 * Ts); // TODO: function conver to norm. frequ.?
	JointArray f_c_fast_norm = contr_param.f_c_fast * (2 * Ts);
	arc_model_ptr = new Iiwa::LBRIiwaModel((unsigned char*)model_binary, model_size, m_Trace, f_c_slow_norm, Ts);
	if (arc_model_ptr->endeffector_body_id < 0) {
		m_Trace.Log(tlError, FENTERA "Body iiwa_link_e could not be found in MuJoCo model!");
		return EXIT_FAILURE;
	}

	Iiwa::JointCTParameter js_param(contr_param);
	Iiwa::CartesianCTParameter ts_param(contr_param);
	Iiwa::SingularPerturbationParameter sp_param(contr_param.K_sp, contr_param.D_sp, f_c_fast_norm);
	Iiwa::JointVector B_fc = arc_model_ptr->get_B();
	Iiwa::FrictionCompensationParameter fc_param(contr_param.L_fc, B_fc, f_c_fast_norm);
	Iiwa::GravityCompParameter gc_param(contr_param.D_gc);

	// create instances
	m_Trace.Log(tlAlways, FLEAVEA "Init ArcLab Controller");
	arc_contr_ptr = new Iiwa::LBRIiwa(
		*arc_model_ptr, Ts, js_param, ts_param, sp_param, fc_param, gc_param);

	state_machine_ptr = new logic::StateMachine(&m_Trace, Ts);

	// Initialize controller
	arc_contr_ptr->set_singular_perturbation_state(m_singular_perturbation_enable);
	arc_contr_ptr->set_friction_compensation_state(m_friction_compensation_enable);

	// Print tool parameters
	Vec3D m_cog_tool = arc_model_ptr->get_endeffector_cog();
	Vec3D m_inertia_tool = arc_model_ptr->get_endeffector_inertia();
	CartesianVector m_tcp_tool = arc_model_ptr->get_endeffector_tcp();
	m_Trace.Log(tlInfo, FLEAVEA "model identifier = %c", arc_model_ptr->model_id);
	m_Trace.Log(tlInfo, FLEAVEA "nbody = %d", arc_model_ptr->m->nbody);
	m_Trace.Log(tlInfo, FLEAVEA "endeffector body id = %d", arc_model_ptr->endeffector_body_id);
	m_Trace.Log(tlInfo, FLEAVEA "base body id = %d", arc_model_ptr->base_body_id);
	m_Trace.Log(tlInfo, FLEAVEA "tool mass = %f kg", arc_model_ptr->get_endeffector_mass());
	m_Trace.Log(tlInfo, FLEAVEA "tool cog  = [%f m, %f m, %f m]", m_cog_tool[0], m_cog_tool[1], m_cog_tool[2]);
	m_Trace.Log(tlInfo, FLEAVEA "tool inertia  = [%f, %f, %f]",
		m_inertia_tool[0], m_inertia_tool[1], m_inertia_tool[2]);
	m_Trace.Log(tlInfo, FLEAVEA "tool tcp  = [%f m, %f m, %f m]",
		m_tcp_tool[0], m_tcp_tool[1], m_tcp_tool[2]);
	m_Trace.Log(tlInfo, FLEAVEA "tool tcp orientation  = [%f °, %f °, %f °]",
		m_tcp_tool[3] * M_PI / 180., m_tcp_tool[4] * M_PI / 180., m_tcp_tool[5] * M_PI / 180.);

	CartesianVector world_param = arc_model_ptr->get_worldparam();
	m_Trace.Log(tlInfo, FLEAVEA "World param translation = [%f m, %f m, %f m]", world_param(0), world_param(1), world_param(2));
	m_Trace.Log(tlInfo, FLEAVEA "World param rotation = [%f °, %f °, %f °]", world_param(3), world_param(4), world_param(5));

	Vec3D rpy;
	rpy << 90., 0., 180.;
	RotationMatrix rot_mat = arc_model_ptr->get_R_from_rpy(rpy);
	mju_printMat(rot_mat.data(), 3, 3, m_Trace);
	mju_printMat(&arc_model_ptr->d->xmat[9 * arc_model_ptr->base_body_id], 3, 3, m_Trace);

	m_Trace.Log(tlAlways, FLEAVEA "SAFEOP TO OP finished");

	// If following call is successful the CycleUpdate method will be called, 
	// possibly even before method has been left.
	hr = FAILED(hr) ? hr : AddModuleToCaller();

	// Cleanup if transition failed at some stage
	if (FAILED(hr))
	{
		RemoveModuleFromCaller();
		DeinitDataPointer();
	}

	m_Trace.Log(tlVerbose, FLEAVEA "hr=0x%08x", hr);
	return hr;
}

